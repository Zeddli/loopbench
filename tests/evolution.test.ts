import assert from "node:assert/strict";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import test from "node:test";
import { evolve, resumeEvolution, evidenceDigest } from "../core/evolution";
import { getCampaign, listCampaigns, saveCampaign, withCampaignLock } from "../core/campaigns";
import { addAdapter, getNode, listTrees, projectRoot, saveNode } from "../core/store";
import { loadBenchmark } from "../core/benchmarks";

test("autonomous rounds use real process evidence, retain rejected siblings and learn into grandchildren with exact call budget", async () => {
  const temporary = await mkdtemp(path.join(projectRoot, ".loopbench-test-evolution-"));
  const previous = process.env.LOOPBENCH_HOME;
  process.env.LOOPBENCH_HOME = temporary;
  try {
    const benchmarkPath = path.join(temporary, "benchmark.json");
    await writeFile(benchmarkPath, JSON.stringify({ id: "evolution-process-fixture", name: "Isolated evolution test", domain: "coding", tasks: ["t1", "t2", "t3"].map(id => ({ id, prompt: "Write a function returning value + 1. Export with module.exports.", cases: [{ args: [2], expected: 3, label: "increment" }, { args: [-1], expected: 0, label: "negative" }] })) }));
    await addAdapter({ id: "evolution-fixture", name: "Process fixture", command: process.execPath, args: [path.join(projectRoot, "tests", "evolution-fixture.mjs")], protocol: "loopbench.task.v1", timeoutMs: 15000 });
    const options = { adapterId: "evolution-fixture", proposerAdapterId: "evolution-fixture", domain: "coding", model: "test-fixture-only", harness: "test-fixture", benchmark: benchmarkPath, rounds: 2, branches: 2, beamWidth: 2, maxCandidates: 4, maxCalls: 29 };
    const campaign = await evolve(options);
    assert.equal(campaign.status, "completed", campaign.error || undefined);
    assert.equal(campaign.completedRounds, 2);
    assert.equal(campaign.candidateIds.length, 4);
    assert.equal(campaign.callsUsed, 29);
    assert.equal(campaign.calls.length, 29);
    assert.ok(campaign.calls.every(call => call.status === "completed"));
    assert.equal(campaign.usage.inputTokens, 58);
    assert.equal(campaign.usage.outputTokens, 87);
    assert.equal(campaign.usage.unknownCostCalls, 0);
    const nodes = await Promise.all(campaign.candidateIds.map(getNode));
    const first = nodes[0]; const rejectedSibling = nodes[1]; const grandchild = nodes[2];
    assert.ok(first && rejectedSibling && grandchild);
    assert.equal(first.status, "accepted");
    assert.equal(rejectedSibling.status, "rejected");
    assert.equal(first.parentId, rejectedSibling.parentId);
    assert.equal(grandchild.parentId, first.id);
    assert.equal(grandchild.status, "accepted");
    assert.equal(grandchild.score, 2 / 3);
    assert.ok(grandchild.learning?.learnedFrom.includes(rejectedSibling.id));
    assert.ok(campaign.proposerRuns[1]?.digest.includes(rejectedSibling.id));
    assert.ok(campaign.proposerRuns[1]?.digest.includes("rejected"));
    assert.ok(campaign.proposerRuns[1]?.digest.includes("increment"));
    const loaded = await getCampaign(campaign.id);
    assert.equal(loaded?.callsUsed, 29);
    assert.deepEqual(await resumeEvolution(campaign.id), loaded);
    await assert.rejects(withCampaignLock(campaign.id, () => withCampaignLock(campaign.id, async () => null)), /active worker/);
    const staleId = "stale-worker-race";
    const staleFile = path.join(temporary, "campaigns", `${staleId}.json.lock`);
    await writeFile(staleFile, "2147483647");
    let activeWorkers = 0; let maxWorkers = 0;
    const work = async () => { activeWorkers++; maxWorkers = Math.max(maxWorkers, activeWorkers); await new Promise(resolve => setTimeout(resolve, 5)); activeWorkers--; };
    const staleAttempts = await Promise.allSettled(Array.from({ length: 12 }, () => withCampaignLock(staleId, work)));
    assert.ok(staleAttempts.every(attempt => attempt.status === "rejected"));
    assert.equal(maxWorkers, 0);
    await rm(staleFile);
    const freshAttempts = await Promise.allSettled(Array.from({ length: 12 }, () => withCampaignLock(staleId, work)));
    assert.ok(freshAttempts.some(attempt => attempt.status === "fulfilled"));
    assert.equal(maxWorkers, 1);
    const benchmark = await loadBenchmark(benchmarkPath);
    const tree = (await listTrees())[0]; assert.ok(tree);
    const digest = evidenceDigest(benchmark, tree.nodes, [first], 2, 3);
    assert.ok(!digest.includes('"expected"'));
    assert.ok(!digest.includes('"cases"'));
    const insufficient = await evolve({ ...options, maxCalls: 2 });
    assert.equal(insufficient.status, "budget_exhausted");
    assert.equal(insufficient.callsUsed, 0);
    assert.equal(insufficient.rootId, null);
    const invalid = await evolve({ ...options, settings: { invalidProposal: "true" } });
    assert.equal(invalid.status, "failed");
    assert.equal(invalid.candidateIds.length, 0);
    assert.equal(invalid.callsUsed, 4);
    assert.match(invalid.error || "", /learning references/);
    const resumeFromParent = await evolve({ ...options, parentId: first.id, maxCalls: 1 });
    assert.equal(resumeFromParent.status, "budget_exhausted");
    assert.equal(resumeFromParent.callsUsed, 0);
    assert.equal(resumeFromParent.rootId, first.id);
    const missingTaskAdapter = await evolve({ ...options, parentId: first.id, adapterId: "missing-adapter" });
    assert.equal(missingTaskAdapter.status, "failed");
    assert.equal(missingTaskAdapter.callsUsed, 0);
    assert.match(missingTaskAdapter.error || "", /Unknown adapter/);
    const missingProposer = await evolve({ ...options, proposerAdapterId: "missing-proposer" });
    assert.equal(missingProposer.status, "failed");
    assert.equal(missingProposer.callsUsed, 0);
    assert.equal(missingProposer.rootId, null);
    const saturated = await evolve({ ...options, settings: { allCorrect: "true" } });
    assert.equal(saturated.status, "saturated");
    assert.equal(saturated.callsUsed, 3);
    assert.equal(saturated.proposerRuns.length, 0);
    const interruptedNode = { ...first, id: "interrupted-evaluation", status: "running", completedAt: null, score: null, comparison: null, tasks: [] } satisfies import("../core/types").NodeRecord;
    await saveNode(interruptedNode);
    const interruptedCampaign = structuredClone(campaign);
    interruptedCampaign.id = "interrupted-missing-benchmark";
    interruptedCampaign.status = "running";
    interruptedCampaign.activeNodeId = interruptedNode.id;
    interruptedCampaign.options.benchmark = path.join(temporary, "deleted-benchmark.json");
    interruptedCampaign.maxCalls = 30; interruptedCampaign.options.maxCalls = 30;
    interruptedCampaign.calls.push({ id: "interrupted-call", kind: "candidate", round: 2, nodeId: interruptedNode.id, taskId: "t1", startedAt: new Date().toISOString(), completedAt: null, status: "reserved", inputTokens: null, outputTokens: null, costUsd: null, error: null });
    interruptedCampaign.callsUsed = 30;
    await saveCampaign(interruptedCampaign);
    const resumed = await resumeEvolution(interruptedCampaign.id);
    assert.equal(resumed.status, "failed");
    assert.equal(resumed.activeNodeId, null);
    assert.equal(resumed.calls.at(-1)?.status, "failed");
    assert.equal((await getNode(interruptedNode.id))?.status, "failed");
    assert.match(resumed.error || "", /ENOENT/);
    const changedNode = { ...interruptedNode, id: "interrupted-changed-evaluation" };
    await saveNode(changedNode);
    const changedCampaign = structuredClone(interruptedCampaign);
    changedCampaign.id = "interrupted-changed-benchmark";
    changedCampaign.activeNodeId = changedNode.id;
    changedCampaign.options.benchmark = benchmarkPath;
    changedCampaign.benchmarkHash = "changed-benchmark-hash";
    const pendingCall = changedCampaign.calls.at(-1); assert.ok(pendingCall);
    pendingCall.nodeId = changedNode.id;
    await saveCampaign(changedCampaign);
    const changedResume = await resumeEvolution(changedCampaign.id);
    assert.equal(changedResume.status, "failed");
    assert.equal(changedResume.calls.at(-1)?.status, "failed");
    assert.equal((await getNode(changedNode.id))?.status, "failed");
    assert.match(changedResume.error || "", /benchmark content changed/);
    assert.equal((await listCampaigns()).length, 9);
  } finally {
    if (previous === undefined) delete process.env.LOOPBENCH_HOME; else process.env.LOOPBENCH_HOME = previous;
    await rm(temporary, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 });
  }
});
